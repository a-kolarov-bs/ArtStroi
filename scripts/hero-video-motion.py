#!/usr/bin/env python3
"""Motion tools for the phone hero video (scripts/build-hero-video-mobile.sh).

The montage public/hero/hero-composite.mp4 is stored at an even 24 fps, but
frames are missing from it at irregular-looking places (the content step
between two stored frames is 2x or 3x the usual one there). Guessing the
pattern by hand went wrong twice, so it is measured from the file itself.

  timing <source.mp4> <out.txt>
      Measures the horizontal content shift between neighbouring stored
      frames. Where the step is ~k times the local median step, k-1 frames
      are missing before that frame. Writes "frame units" per line: the
      frame's time in source-frame units (frame 0 = 0). Where the camera
      barely moves (local median below MIN_STEP) a single step cannot be
      read, so each frame takes the step measured for its phase of the
      repeating pattern (period found from the data).

  check <video.mp4>
      Fails (exit 1) unless, on a 390x844 phone screen, the content moves
      at mean <= 80 px/s, peak (0.5 s average) <= 150 px/s, and no phase of
      the 1 s (24 frames) or 2.5 s (60 frames) cycle is faster than PHASE_MAX
      times the average phase (speed of each frame relative to its local 1 s
      median), over the whole clip. That is the check for the "jolt every N
      seconds" class of fault. PHASE_MAX is 1.5: the owner accepted the 1.44x
      left on the 2.5 s cycle by the interpolation (26.11.2026); 807bc6d was 1.95x.

FFMPEG=/path/to/ffmpeg (default: ffmpeg). Standard library only.
"""
import os
import statistics as st
import subprocess
import sys

PHASE_MAX = 1.5  # see "check" above

FFMPEG = os.environ.get("FFMPEG", "ffmpeg")
MIN_STEP = 1.5  # source px per stored frame; below it a gap is invisible


def frames(path, w, h):
    p = subprocess.Popen(
        [FFMPEG, "-v", "error", "-i", path, "-vf", f"scale={w}:{h},format=gray",
         "-f", "rawvideo", "-"], stdout=subprocess.PIPE)
    while True:
        buf = p.stdout.read(w * h)
        if len(buf) < w * h:
            break
        yield buf
    p.wait()


def profile(buf, w, h):
    """Horizontal gradient of the column sums (middle rows), mean removed."""
    cols = [0.0] * w
    for y in range(h // 8, h - h // 8, 2):
        row = buf[y * w:(y + 1) * w]
        for x in range(w):
            cols[x] += row[x]
    g = [cols[x + 1] - cols[x] for x in range(w - 1)]
    m = sum(g) / len(g)
    return [v - m for v in g]


def shift(a, b, r):
    """Sub-pixel shift of b against a (positive = content moved right)."""
    n = len(a)
    best = [sum(a[x] * b[x + s] for x in range(r, n - r)) for s in range(-r, r + 1)]
    i = max(range(len(best)), key=best.__getitem__)
    d = 0.0
    if 0 < i < len(best) - 1:
        y0, y1, y2 = best[i - 1], best[i], best[i + 1]
        den = y0 - 2 * y1 + y2
        d = (y0 - y2) / (2 * den) if den else 0.0
    return i - r + d


def steps(path, w, h, r):
    prev, out = None, []
    for buf in frames(path, w, h):
        pr = profile(buf, w, h)
        if prev is not None:
            out.append(shift(prev, pr, r))
        prev = pr
    return out  # out[i] = step from frame i to frame i+1


def ratios(s, gaps):
    """Step into each frame / local median step of its neighbours (gaps left out).
    Only frames where the camera moves enough and in the same direction."""
    r = {}
    for i in range(1, len(s) + 1):
        nb = [s[j - 1] for j in range(i - 6, i + 7)
              if 1 <= j <= len(s) and j != i and j not in gaps]
        m = st.median(abs(x) for x in nb)
        if m >= MIN_STEP and s[i - 1] * st.median(nb) > 0:
            r[i] = abs(s[i - 1]) / m
    return r


def timing(src, dst):
    s = steps(src, 864, 496, 48)
    n = len(s) + 1
    # One frame on its own is noisy (a gap reads 1.4x-3.2x), so: 1) find the
    # gaps roughly, 2) re-measure against neighbours without gaps, 3) find the
    # repeat period of the pattern from the data (autocorrelation), 4) take
    # the median ratio of each phase over the whole clip and round it to the
    # number of frame times the step spans (unrounded medians were tried:
    # they break the even output grid and measured worse).
    r = ratios(s, {i for i, x in ratios(s, set()).items() if x > 1.4})
    ac = {}
    for p in range(2, 61):
        pr = [(r[i] - 1) * (r[i + p] - 1) for i in r if i + p in r]
        ac[p] = sum(pr) / len(pr)
    period = min(p for p in ac if ac[p] >= 0.75 * max(ac.values()))
    ph = {}
    for i, x in r.items():
        ph.setdefault(i % period, []).append(x)
    k = {p: float(max(1, round(st.median(v)))) for p, v in ph.items()}
    units = [0.0]
    for i in range(1, n):
        units.append(round(units[-1] + k.get(i % period, 1.0), 2))
    with open(dst, "w") as f:
        f.write("# frame units: time of each stored frame of hero-composite.mp4 in\n"
                "# source-frame units (generated by scripts/hero-video-motion.py timing)\n"
                f"# period {period} stored frames; step per phase (median ratio, frames measured):\n# "
                + " ".join(f"{p}:{k[p]:.0f}({st.median(ph[p]):.2f}/{len(ph[p])})" for p in sorted(ph))
                + "\n")
        for i, u in enumerate(units):
            f.write(f"{i} {u:.2f}\n")
    print(f"{n} frames -> {units[-1]:.2f} units; period {period}; steps >1.3 at phases "
          + " ".join(f"{p}:{k[p]:.2f}" for p in sorted(k) if k[p] > 1.3))


def check(video):
    fps = 24
    w = 360
    s = steps(video, w, 640, 14)
    scale = max(390 / 720, 844 / 1280) * 1.02
    v = [abs(x) * (720 / w) * scale * fps for x in s]  # screen px/s per frame
    mean = st.mean(v)
    n = fps // 2
    peak = max(sum(v[i:i + n]) / n for i in range(len(v) - n))
    ok = mean <= 80 and peak <= 150
    print(f"frames {len(v) + 1}  mean {mean:.1f} px/s (<=80)  peak(0.5 s) {peak:.1f} px/s (<=150)")
    # speed relative to the local 1 s median, so the slow trend does not count
    rel = {}
    for i, x in enumerate(v):
        loc = st.median(v[max(0, i - 12):i + 13])
        if loc >= 10:
            rel[i + 1] = x / loc
    for period, name in ((24, "1 s"), (60, "2.5 s")):
        ph = {}
        for i, r in rel.items():
            ph.setdefault(i % period, []).append(r)
        means = {p: st.mean(r) for p, r in ph.items()}
        avg = st.mean(means.values())
        top = max(means, key=means.get)
        ratio = means[top] / avg
        good = ratio <= PHASE_MAX
        ok = ok and good
        print(f"phase {name:>5} (mod {period}): fastest phase {top} = {ratio:.2f}x average (<={PHASE_MAX}) "
              + ("OK" if good else "FAIL"))
        print("   " + " ".join(f"{p}:{means[p] / avg:.2f}" for p in sorted(means)))
    print("OK" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "timing":
        timing(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 3 and sys.argv[1] == "check":
        sys.exit(check(sys.argv[2]))
    else:
        print(__doc__)
        sys.exit(2)
