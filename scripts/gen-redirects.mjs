#!/usr/bin/env node
// Generates public/_redirects (Netlify format, 301) from the old site's
// addresses to the new pages.
//
// Projects: every `source_url` in src/data/legacy-projects.json
// (https://www.artstroismolian.com/projects/progectN.html) → /proekti/<slug>/.
// The old site also had English copies progectNen.html for N = 1..52; they go
// to the same Bulgarian page (there is no English version yet).
// Static pages: the old site's menu (checked with curl on 25.11.2026).
//
// Usage: node scripts/gen-redirects.mjs [--check]
//   --check  exits 1 if public/_redirects differs from what would be generated.
//
// The file is for Netlify. On another host convert it (Vercel: "redirects" in
// vercel.json; Cloudflare Pages reads the same _redirects format).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public/_redirects');
const legacy = JSON.parse(readFileSync(join(root, 'src/data/legacy-projects.json'), 'utf8'));

// Highest N for which the old site has projects/progectNen.html (53–55 return 404).
const LAST_EN_PROJECT = 52;

const STATIC = [
  // [old path, new path, what the old page was]
  // /index.html is not listed: dist/index.html exists, so the host serves it
  // and a non-forced rule would never fire.
  ['/main.html', '/za-nas/', 'Основна дейност (За нас)'],
  ['/sert.html', '/za-nas/', 'Сертификати'],
  ['/partners.html', '/za-nas/', 'Партньори'],
  ['/services.html', '/uslugi/', 'Услуги'],
  ['/project.html', '/proekti/', 'Всички проекти'],
  ['/contacts.html', '/kontakti/', 'Контакти'],
  ['/map2.html', '/kontakti/', 'Карта на офиса'],
  ['/indexen.html', '/', 'Home (EN)'],
  ['/mainen.html', '/za-nas/', 'About (EN)'],
  ['/serten.html', '/za-nas/', 'Certificates (EN)'],
  ['/partnersen.html', '/za-nas/', 'Partners (EN)'],
  ['/servicesen.html', '/uslugi/', 'Services (EN)'],
  ['/projecten.html', '/proekti/', 'Projects (EN)'],
  ['/contactsen.html', '/kontakti/', 'Contacts (EN)'],
];

const bg = [];
const en = [];
const seen = new Set();
for (const p of legacy) {
  const url = new URL(p.source_url);
  const m = url.pathname.match(/^\/projects\/progect(\d+)\.html$/);
  if (!m) throw new Error(`gen-redirects: unexpected source_url "${p.source_url}" (id ${p.id})`);
  if (!p.slug) throw new Error(`gen-redirects: project ${p.id} has no slug`);
  if (seen.has(url.pathname)) throw new Error(`gen-redirects: duplicate source_url ${url.pathname}`);
  seen.add(url.pathname);
  const n = Number(m[1]);
  bg.push({ n, line: `${url.pathname}  /proekti/${p.slug}/  301` });
  if (n <= LAST_EN_PROJECT) en.push({ n, line: `/projects/progect${n}en.html  /proekti/${p.slug}/  301` });
}
bg.sort((a, b) => a.n - b.n);
en.sort((a, b) => a.n - b.n);

const pad = (s) => s.padEnd(22);
const text = [
  '# Old artstroismolian.com addresses → new pages. 301 = moved permanently.',
  '# Generated by scripts/gen-redirects.mjs from src/data/legacy-projects.json. Do not edit by hand.',
  '# Format: Netlify. On another host convert it (see CLAUDE.md).',
  '# www → bare domain and http → https are set in the host settings, not here.',
  '',
  `# Static pages (${STATIC.length})`,
  // Netlify allows comments only on their own line.
  ...STATIC.flatMap(([from, to, what]) => [`# ${what}`, `${pad(from)}  ${pad(to)}  301`]),
  '',
  `# Projects (${bg.length})`,
  ...bg.map((x) => x.line),
  '',
  `# Projects, English copies (${en.length})`,
  ...en.map((x) => x.line),
  '',
].join('\n');

// The same rules for Vercel (vercel.json `redirects`), which ignores _redirects.
// `permanent: true` = 308; search engines treat it like 301.
const vercelOut = join(root, 'vercel.json');
const vercelText = JSON.stringify({
  $schema: 'https://openapi.vercel.sh/vercel.json',
  // The *.vercel.app demo stays out of search results; the real domain is
  // indexed normally once it points here (no code change needed).
  headers: [
    {
      source: '/(.*)',
      has: [{ type: 'host', value: '(?<sub>.*)\\.vercel\\.app' }],
      headers: [{ key: 'X-Robots-Tag', value: 'noindex, nofollow' }],
    },
  ],
  redirects: text
    .split('\n')
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => {
      const [source, destination] = l.trim().split(/\s+/);
      return { source, destination, permanent: true };
    }),
}, null, 2) + '\n';

if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  const curVercel = existsSync(vercelOut) ? readFileSync(vercelOut, 'utf8') : '';
  if (cur !== text || curVercel !== vercelText) {
    console.error('gen-redirects: public/_redirects or vercel.json is out of date. Run: node scripts/gen-redirects.mjs');
    process.exit(1);
  }
  console.log(`gen-redirects: OK (${STATIC.length} static + ${bg.length} projects + ${en.length} EN)`);
} else {
  writeFileSync(out, text);
  writeFileSync(vercelOut, vercelText);
  console.log(`gen-redirects: wrote ${STATIC.length} static + ${bg.length} projects + ${en.length} EN = ${STATIC.length + bg.length + en.length} rules`);
}
