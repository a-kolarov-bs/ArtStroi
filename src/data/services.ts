// /uslugi (everything else), so the two pages always name the same six.
//
// `refCat` is set only when a project category matches the service one to
// one. Then /uslugi shows the number of cards the linked /proekti filter
// shows. A service without its own category (refCat: null) shows no number
// and links to all objects: a borrowed category would count projects that
// are not this kind of work. scripts/check-categories.mjs reads these
// refCat values and checks dist/.
